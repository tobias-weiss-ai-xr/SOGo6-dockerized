def translate_obj(obj, translation_map):
    """Recursively translate leaf string values in a JSON-like dict."""
    if isinstance(obj, dict):
        result = {}
        for k, v in obj.items():
            if isinstance(v, str):
                # Check if the parent key is one that should be translated
                # We translate ALL leaf string values except 'context' and 'description' keys
                # (those are metadata, not displayed to users)
                if k in ('context', 'description') and isinstance(v, str):
                    # Keep metadata as-is (still English for dev reference)
                    result[k] = v
                else:
                    result[k] = translation_map.get(v, v)
            elif isinstance(v, (dict, list)):
                result[k] = translate_obj(v, translation_map)
            else:
                result[k] = v
        return result
    elif isinstance(obj, list):
        return [translate_obj(item, translation_map) if isinstance(item, (dict, list)) else translation_map.get(item, item) if isinstance(item, str) else item for item in obj]
    return obj


def main():
    src_dir = os.path.join(BASE_DIR, SOURCE_LOCALE)

    for locale in TARGET_LOCALES:
        if locale == 'de':
            translation_map = DE
        elif locale == 'fr':
            translation_map = FR
        elif locale == 'es':
            translation_map = ES
        else:
            continue

        tgt_dir = os.path.join(BASE_DIR, locale)

        # Walk source directory
        for root, dirs, files in os.walk(src_dir):
            for fname in files:
                if not fname.endswith('.json'):
                    continue

                src_file = os.path.join(root, fname)
                rel_path = os.path.relpath(src_file, src_dir)
                tgt_file = os.path.join(tgt_dir, rel_path)

                with open(src_file, 'r', encoding='utf-8') as f:
                    data = json.load(f)

                translated = translate_obj(data, translation_map)

                os.makedirs(os.path.dirname(tgt_file), exist_ok=True)
                with open(tgt_file, 'w', encoding='utf-8', newline='') as f:
                    json.dump(translated, f, indent=4, ensure_ascii=False)
                print(f"✓ {locale}/{rel_path} ({count_leaves(translated)} strings)")

        print(f"\n✅ Generated {locale} translations\n")


def count_leaves(obj):
    """Count leaf string values in a JSON-like structure."""
    count = 0
    if isinstance(obj, dict):
        for v in obj.values():
            if isinstance(v, str):
                count += 1
            elif isinstance(v, (dict, list)):
                count += count_leaves(v)
    elif isinstance(obj, list):
        for item in obj:
            count += count_leaves(item)
    return count


